def run_linear(
    d_in: int,
    d_out: int,
    weights: Float[Tensor, " d_out d_in"],
    in_features: Float[Tensor, " ... d_in"],
) -> Float[Tensor, " ... d_out"]:
    model = LinearModule(d_in, d_out)
    model.load_state_dict({"weight": weights})
    return model(in_features)


